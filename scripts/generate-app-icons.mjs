#!/usr/bin/env node
/**
 * Regenerate launcher icons from `buildResources/icons/app-icon.png`.
 *
 * The Android project shipped Tauri's default teal/amber logo: `tauri icon` had never
 * been run against `gen/android`, and the generated project has no adaptive icon, so
 * Android 8+ fell back to the stale legacy `ic_launcher.png` in each mipmap bucket.
 *
 * What this writes:
 *   - src-tauri/icons             desktop and store icons, via `tauri icon`
 *   - gen/android res mipmaps     legacy, round, and adaptive-foreground launcher icons
 *   - gen/android mipmap-anydpi-v26   the adaptive icon itself
 *   - gen/android values/ic_launcher_background.xml
 *
 * The source is a 1024x1024 transparent PNG of the potato-over-tomato mark, composed
 * from `buildResources/icons/potato-tomato.svg` (see docs/brand.md). Android masks
 * adaptive icons hard — circle, squircle, teardrop — so the foreground layer is inset
 * to the 66% safe zone rather than filling the canvas.
 *
 * Needs ImageMagick (`magick`). Icons are committed, so this is a one-off tool, not a
 * build step.
 *
 * Usage: node scripts/generate-app-icons.mjs [--skip-tauri]
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.join(import.meta.dirname, '..');
const SOURCE = path.join(ROOT, 'buildResources/icons/app-icon.png');
const ANDROID_RES = path.join(ROOT, 'src-tauri/gen/android/app/src/main/res');

/** Warm cream behind the mark. Both the tan potato and the red tomato read against it. */
const BACKGROUND = '#FFF3E2';

/**
 * Android's adaptive icon draws a 108dp layer and masks all but the centre 72dp, then
 * shrinks that again for animation headroom. 66% keeps the mark inside every mask.
 */
const SAFE_ZONE = 0.66;

/** Launcher icon size in px per density bucket (48dp baseline). */
const DENSITIES = {
	mdpi: 48,
	hdpi: 72,
	xhdpi: 96,
	xxhdpi: 144,
	xxxhdpi: 192
};

function magick(args) {
	execFileSync('magick', args, { stdio: ['ignore', 'ignore', 'inherit'] });
}

function assertSource() {
	if (fs.existsSync(SOURCE)) return;
	console.error(`[icons] missing source: ${path.relative(ROOT, SOURCE)}`);
	process.exit(1);
}

/** Legacy square icon: the mark on the brand background, no mask applied. */
function writeLegacy(out, size) {
	magick([
		'-size',
		`${size}x${size}`,
		`xc:${BACKGROUND}`,
		'(',
		SOURCE,
		'-resize',
		`${Math.round(size * 0.86)}x${Math.round(size * 0.86)}`,
		')',
		'-gravity',
		'center',
		'-composite',
		out
	]);
}

/** Pre-Android-8 launchers that ask for a round icon get a real circle, not a square. */
function writeRound(out, size) {
	const r = size / 2;
	magick([
		'-size',
		`${size}x${size}`,
		`xc:${BACKGROUND}`,
		'(',
		SOURCE,
		'-resize',
		`${Math.round(size * 0.74)}x${Math.round(size * 0.74)}`,
		')',
		'-gravity',
		'center',
		'-composite',
		'(',
		'-size',
		`${size}x${size}`,
		'xc:none',
		'-fill',
		'white',
		'-draw',
		`circle ${r - 0.5},${r - 0.5} ${r - 0.5},0`,
		')',
		'-alpha',
		'set',
		'-compose',
		'DstIn',
		'-composite',
		out
	]);
}

/** Adaptive foreground: transparent, mark inset to the safe zone. */
function writeForeground(out, size) {
	/* Foreground layers are 108dp where the icon is 48dp — 2.25x the launcher size. */
	const canvas = Math.round(size * 2.25);
	magick([
		SOURCE,
		'-resize',
		`${Math.round(canvas * SAFE_ZONE)}x${Math.round(canvas * SAFE_ZONE)}`,
		'-background',
		'none',
		'-gravity',
		'center',
		'-extent',
		`${canvas}x${canvas}`,
		out
	]);
}

function writeAndroidIcons() {
	for (const [density, size] of Object.entries(DENSITIES)) {
		const dir = path.join(ANDROID_RES, `mipmap-${density}`);
		fs.mkdirSync(dir, { recursive: true });
		writeLegacy(path.join(dir, 'ic_launcher.png'), size);
		writeRound(path.join(dir, 'ic_launcher_round.png'), size);
		writeForeground(path.join(dir, 'ic_launcher_foreground.png'), size);
		console.log(`[icons] mipmap-${density} (${size}px)`);
	}

	const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-app-icons.mjs — do not hand-edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
`;
	const anydpi = path.join(ANDROID_RES, 'mipmap-anydpi-v26');
	fs.mkdirSync(anydpi, { recursive: true });
	for (const name of ['ic_launcher.xml', 'ic_launcher_round.xml']) {
		fs.writeFileSync(path.join(anydpi, name), adaptive);
		console.log(`[icons] mipmap-anydpi-v26/${name}`);
	}

	const values = path.join(ANDROID_RES, 'values/ic_launcher_background.xml');
	fs.writeFileSync(
		values,
		`<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-app-icons.mjs — do not hand-edit. -->
<resources>
    <color name="ic_launcher_background">${BACKGROUND}</color>
</resources>
`
	);
	console.log('[icons] values/ic_launcher_background.xml');

	/*
	 * The Tauri project template ships its own logo as vector drawables that nothing
	 * references once the adaptive icon above exists. Leaving them behind is how the
	 * default icon survived a rebrand in the first place.
	 */
	for (const stale of [
		'drawable/ic_launcher_background.xml',
		'drawable-v24/ic_launcher_foreground.xml'
	]) {
		const p = path.join(ANDROID_RES, stale);
		if (fs.existsSync(p)) {
			fs.rmSync(p);
			console.log(`[icons] removed stale ${stale}`);
		}
	}
}

function writeDesktopIcons() {
	console.log('[icons] tauri icon (desktop + store sizes)');
	execFileSync('pnpm', ['tauri', 'icon', path.relative(ROOT, SOURCE)], {
		cwd: ROOT,
		stdio: 'inherit'
	});
}

assertSource();
if (!process.argv.includes('--skip-tauri')) writeDesktopIcons();
/* After `tauri icon`, which overwrites the Android mipmaps with unmasked squares. */
writeAndroidIcons();
console.log('[icons] done');
